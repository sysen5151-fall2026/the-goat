-- ============================================================
-- Wayly NYC — app tables (additive; safe to re-run).
--
-- Shares Supabase Auth, public.profiles and public.user_roles with Wayly
-- Beijing (mvp2): one Wayly account works in both apps, and the existing
-- on_auth_user_created trigger creates the profile + 'user' role.
-- NYC data lives in its own nyc_* tables so it never mixes with Beijing data.
--
-- Access model (same as mvp2): RLS on, no anon/authenticated grants. Only the
-- server (secret key) reads/writes, after lib/auth.ts verifies the caller's JWT
-- and every query is scoped by user_id in server code.
-- ============================================================

-- Profile avatars use the shared profile row; keep this additive for existing Wayly accounts.
alter table public.profiles add column if not exists avatar_emoji text;

create table if not exists public.nyc_itineraries (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 200),
  plan_mode text,
  itinerary_json jsonb not null,
  created_at timestamptz not null default now()
);
create index if not exists nyc_itineraries_user_created_idx on public.nyc_itineraries (user_id, created_at desc);

create table if not exists public.nyc_user_preferences (
  user_id uuid primary key references auth.users(id) on delete cascade,
  total_budget_usd integer not null check (total_budget_usd >= 0 and total_budget_usd <= 10000),
  party_size integer not null default 2 check (party_size between 1 and 8),
  interests jsonb not null default '[]'::jsonb,
  transport_preference text not null,
  walking_preference text not null,
  dining text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.nyc_feedback (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  itinerary_id text not null,
  rating text not null check (rating in ('helpful', 'not_helpful')),
  satisfaction_score integer check (satisfaction_score between 1 and 5),
  trust_score integer check (trust_score between 1 and 5),
  issue_type text,
  note text check (note is null or char_length(note) <= 500),
  itinerary_version text,
  data_version_id text,
  created_at timestamptz not null default now()
);
create index if not exists nyc_feedback_created_idx on public.nyc_feedback (created_at desc);

create table if not exists public.nyc_daily_model_call_budget (
  date_utc date primary key,
  call_count integer not null default 0 check (call_count >= 0),
  updated_at timestamptz not null default now()
);

alter table public.nyc_itineraries enable row level security;
alter table public.nyc_user_preferences enable row level security;
alter table public.nyc_feedback enable row level security;
alter table public.nyc_daily_model_call_budget enable row level security;

revoke all on table public.nyc_itineraries, public.nyc_user_preferences, public.nyc_feedback, public.nyc_daily_model_call_budget from anon, authenticated;

-- updated_at is written explicitly by the server on every upsert (lib/nyc-account.ts).

-- Atomically reserve one real DeepSeek call for today (UTC). Separate from the
-- Beijing counter so the two apps don't share one daily cap.
create or replace function public.nyc_reserve_daily_model_call_budget(p_limit integer, p_date date default (current_date))
returns table(allowed boolean, call_count integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  current_count integer;
begin
  insert into public.nyc_daily_model_call_budget (date_utc, call_count) values (p_date, 0)
  on conflict (date_utc) do nothing;
  select d.call_count into current_count from public.nyc_daily_model_call_budget d where d.date_utc = p_date for update;
  if current_count < p_limit then
    update public.nyc_daily_model_call_budget d set call_count = d.call_count + 1, updated_at = now() where d.date_utc = p_date;
    return query select true, current_count + 1;
  else
    return query select false, current_count;
  end if;
end;
$$;

revoke all on function public.nyc_reserve_daily_model_call_budget(integer, date) from public, anon, authenticated;
grant execute on function public.nyc_reserve_daily_model_call_budget(integer, date) to service_role;
